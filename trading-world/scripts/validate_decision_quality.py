"""Validate the S6 decision-quality score (learning/quality.py) and write the evidence to
reports/phase25/decision_quality_validation.md.

Checks:
  1. Known cases: staying out (0), the growth-optimal size (1), excessive sizes (negative,
     ruinous from 9.5x).
  2. The formula g(G) agrees with direct Monte Carlo of the S6 return process.
  3. The formula agrees with the trading simulator itself: an agent holding a constant size G
     earns, on average, g(G) per decision as its R1 reward.
  4. Luck-independence: identical decisions on two different market paths get identical scores,
     although their realised profits differ; a lucky ruinous agent that happens to profit still
     scores as ruinous.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tradeworld.interface.actions import ActionMapper  # noqa: E402
from tradeworld.learning import synthetic_tasks as st  # noqa: E402
from tradeworld.learning.env import TradeWorldEnv  # noqa: E402
from tradeworld.learning.quality import KnownMarket, episode_expected_growth, quality_metrics  # noqa: E402


def simulator_growth(task, G: float, episodes: int, L: int = 1000) -> tuple[float, float, int]:
    """Mean R1 reward per decision of a constant-size agent in the real simulator."""
    env = TradeWorldEnv(task.md, task.profile, reward="R1", episode_decisions=L, random_start=False,
                        **task.env_kwargs)
    u = ActionMapper.primary(1).u_for_gross(G) if G > 0 else -1.0
    a = np.array([1.0 if G > 0 else 0.0, u])
    hi = len(env.dec_all) - L - 1
    rewards, deaths = [], 0
    for k, k0 in enumerate(np.linspace(0, hi, episodes).astype(int)):
        env.reset(seed=k, options={"start_decision": int(k0)})
        done = False
        while not done:
            _, r, te, tr, _ = env.step(a)
            rewards.append(r)
            done = te or tr
        deaths += int(te)
    x = np.array(rewards)
    return float(x.mean()), float(x.std(ddof=1) / math.sqrt(len(x))), deaths


def main():
    task = st.build("S6", 0, 200_000)
    mk = KnownMarket.from_task(task)
    Gs, gs = mk.optimal()
    L = ["# S6 decision-quality score: validation\n",
         f"Generated by `scripts/validate_decision_quality.py`. Market parameters: mu = {mk.mu}, sigma = {mk.sigma}, "
         f"crash probability = {mk.crash_prob:.6f} per decision, crash size = {mk.crash:.0%}.\n",
         "## 1. Known cases\n",
         f"Growth-optimal size G* = **{Gs:.3f}x**, expected log growth g(G*) = {gs:.4e} per decision. "
         f"Ruinous from {mk.ruin_long():.2f}x long (one crash crosses the 5% death line).\n",
         "| Size | g(G) per decision | Quality q = g/g* | Ruinous | Episode quality Q (1,000 decisions, 2,000 paths) | Episode death rate |",
         "|---|---|---|---|---|---|"]
    for G in [0, 0.5, 1, 2, Gs, 4, 6, 8, 9, 9.5, 10, 20, -1]:
        g = mk.growth(G)[0]
        f = episode_expected_growth(np.full(1000, G), mk, 2000, 0)
        Q = f.mean() / (1000 * gs)
        L.append(f"| {G:.2f}x | {g:.3e} | {g / gs:.3f} | {'yes' if mk.ruinous(G) else 'no'} | {Q:.3f} | "
                 f"{np.mean(f <= math.log(0.05) + 1e-12):.0%} |")
    L += ["", "Staying out scores exactly 0. The optimum scores 1 per decision (0.97 per episode: rare double "
          "crashes can still end an account at 2.9x). Larger sizes score negative; from 10x every size means "
          "near-certain death (96% of episodes) and scores between -9 and -10, and differences inside that "
          "band carry no meaning.\n"]

    L += ["## 2. Formula vs direct Monte Carlo of the return process\n",
          "| Size | g(G) formula | Monte Carlo mean (4,000,000 draws) | Standard error | Difference / SE |", "|---|---|---|---|---|"]
    n = 4_000_000
    for sample in (1, 2):
        rng = np.random.default_rng(sample)
        crash = rng.random(n) < mk.crash_prob
        r = np.where(crash, math.log(1 - mk.crash), mk.m + mk.sigma * rng.standard_normal(n))
        L.append(f"| *sample {sample}: {int(crash.sum()):,} crashes (expected {n * mk.crash_prob:,.0f})* | | | | |")
        for G in [0.5, 1, Gs, 5, 8, -1]:
            x = np.log(1 + G * np.expm1(r))
            mc, se = x.mean(), x.std(ddof=1) / math.sqrt(n)
            g = mk.growth(G)[0]
            L.append(f"| {G:.2f}x | {g:.4e} | {mc:.4e} | {se:.1e} | {(mc - g) / se:+.2f} |")
    L += ["", "Within one sample every size reuses the same draws, so their differences share one sampling error "
          "(they move together, set mostly by how many crashes the sample happened to contain). Across the two "
          "independent samples the differences fall on both sides of zero and stay within about 2 standard errors.\n"]

    L += ["## 3. Formula vs the trading simulator\n",
          "A constant-size agent in the real S6 environment (1,000-decision episodes); its average R1 reward per "
          "decision should equal g(G).\n",
          "| Size | g(G) formula | Simulator mean reward | Standard error | Difference / SE | Deaths |", "|---|---|---|---|---|---|"]
    for G, eps in [(0.0, 5), (1.0, 60), (Gs, 60), (5.0, 60)]:
        m, se, d = simulator_growth(task, G, eps)
        g = mk.growth(G)[0]
        L.append(f"| {G:.2f}x | {g:.4e} | {m:.4e} | {se:.1e} | {(m - g) / se:+.2f} | {d} of {eps} |"
                 if se > 0 else f"| {G:.2f}x | {g:.4e} | {m:.4e} | 0 | exact | {d} of {eps} |")
    L.append("")

    L += ["## 4. Luck-independence\n"]
    G_seq = np.r_[np.full(500, 2.0), np.full(500, 12.0)]

    def outcome(r):                                   # realised result with the 5% death line
        eq = np.cumsum(np.log(np.maximum(1 + G_seq * np.expm1(r), 1e-300)))
        dead = np.flatnonzero(eq <= math.log(0.05))
        return ("account died at decision %d" % (dead[0] + 1)) if len(dead) else ("account grew %+.0f%%" % (100 * math.expm1(eq[-1])))
    found = {}
    for seed in range(500):
        rng = np.random.default_rng(seed)
        crash = rng.random(1000) < mk.crash_prob
        r = np.where(crash, math.log(1 - mk.crash), mk.m + mk.sigma * rng.standard_normal(1000))
        key = "ruin" if crash[500:].any() else "lucky"
        found.setdefault(key, outcome(r))
        if len(found) == 2:
            break
    a = quality_metrics(G_seq, mk)
    L.append(f"The same 1,000 decisions (500 at 2x, then 500 at 12x) on two different market paths: on one the "
             f"{found['ruin']}; on the other (no crash in the second half) the {found['lucky']}. The scores are "
             f"identical on both, because they use only the decisions: quality {a['quality']:.3f}, ruinous share "
             f"{a['ruinous_share']:.0%}, episode quality {a['episode_quality']:.2f}.\n")
    lucky = None
    for seed in range(200):
        rng = np.random.default_rng(seed)
        crash = rng.random(1000) < mk.crash_prob
        if not crash.any():
            r = mk.m + mk.sigma * rng.standard_normal(1000)
            lucky = float(np.sum(np.log(1 + 12.0 * np.expm1(r))))
            break
    q12 = quality_metrics(np.full(1000, 12.0), mk)
    L.append(f"A lucky gambler at a constant 12x on a path that happens to contain no crash ends with realised log "
             f"growth {lucky:+.2f} (a large profit). Its scores: ruinous share {q12['ruinous_share']:.0%}, episode "
             f"quality {q12['episode_quality']:.2f}. The score judges the decision, not the outcome.\n")
    out = ROOT / "reports" / "phase25" / "decision_quality_validation.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
